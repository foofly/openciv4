#!/usr/bin/env python3
"""Generate embedded Vulkan shaders from the same HLSL as gen_msl.py.

Requires glslang, spirv-val and SPIRV-Cross (setup_linux.py --shader-tools).
The GLSL intermediate combines HLSL's separate textures and samplers to match
SDL's Vulkan descriptors. Generated output is checked in; players need no tools.
"""
import argparse
import re
import shutil
import struct
import tempfile
from pathlib import Path

from gen_msl import ENTRIES, ROOT, SOURCES, run

OUT = ROOT / "src/render/SpirvShaders.inc"


def generate():
    def tool(local, name):
        path = ROOT / "external" / local
        return str(path) if path.exists() else shutil.which(name)
    glslang = tool("glslang-build/StandAlone/glslang", "glslang") or shutil.which("glslangValidator")
    cross = tool("spirv-cross-build/spirv-cross", "spirv-cross")
    validator = tool("glslang-build/External/spirv-tools/tools/spirv-val", "spirv-val")
    if not glslang:
        raise SystemExit("Install glslang (see README)")
    if not cross or not validator:
        raise SystemExit("Run python3 tools/setup_linux.py --shader-tools")
    out = ["// Generated by tools/shaders/gen_spirv.py. Do not edit.\n"]
    records = []
    with tempfile.TemporaryDirectory() as directory:
        tmp = Path(directory)
        for file, entry, stage, _ in ENTRIES:
            hlsl, spv, glsl, final = (tmp / (entry + suffix) for suffix in (".hlsl", ".spv", ".glsl", ".vulkan.spv"))
            # HLSL permits uint3 at byte 52; std140 requires a 16-byte vector
            # alignment. Scalar padding preserves the host's exact byte layout.
            source_hlsl = SOURCES[file].replace("uint3 terrainPad;", "uint terrainPad0; uint terrainPad1; uint terrainPad2;")
            hlsl.write_text(source_hlsl, encoding="utf-8")
            uniform_set = 1 if stage == "vert" else 3
            resource_set = uniform_set - 1
            run(glslang, "-D", "-V", "--hlsl-iomap", "--hlsl-offsets", f"-DUNIFORMS=space{uniform_set}",
                "-S", stage, "-e", entry, "--source-entrypoint", entry, "-o", spv, hlsl)
            source = run(cross, spv, "--version", "450", "--no-es", "--combined-samplers-inherit-bindings")
            # Desktop GLSL omits descriptor sets. Restore SDL's resource/uniform sets.
            def descriptor(match):
                layout, declaration = match.groups()
                uniform = "uniform" in declaration and not re.search(r"\b[ui]?sampler\w*\b", declaration)
                return f"layout(set = {uniform_set if uniform else resource_set}, {layout}){declaration}"
            source = re.sub(r"layout\(([^\n)]*\bbinding\s*=\s*\d+[^\n)]*)\)([^\n]+)", descriptor, source)
            glsl.write_text(source, encoding="utf-8")
            # GLSL's entry point is main; the embedded record retains the HLSL lookup key.
            run(glslang, "-V", "-S", stage, "-o", final, glsl)
            run(validator, final)
            data = final.read_bytes()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            symbol = "kSpirv" + entry
            out.append(f"alignas(4) static const uint32_t {symbol}[] = {{\n")
            for offset in range(0, len(words), 8):
                out.append("\t" + ", ".join(f"0x{v:08x}" for v in words[offset:offset + 8]) + ",\n")
            out.append("};\n")
            records.append(f'\t{{ "{file}", "{entry}", {symbol}, sizeof({symbol}) }},\n')
            print(file, entry, len(data), "bytes")
    out.append("static const SpirvShader kSpirvShaders[] = {\n" + "".join(records) + "};\n")
    return "".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in shaders differ")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != output:
            raise SystemExit("Vulkan shaders are stale: run tools/shaders/gen_spirv.py")
    else:
        OUT.write_text(output)


if __name__ == "__main__":
    main()
